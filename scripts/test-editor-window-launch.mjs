#!/usr/bin/env node

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const read = (path) => readFileSync(join(root, path), 'utf8')

const main = read('src/main.tsx')
const quickEditorView = read('src/views/QuickEditorDetachedView.tsx')
const editorWindowApi = read('src/workspace/editorWindow.ts')
const editorWindowManager = read('src/workspace/windowManager/editorWindow.ts')
const editorBridge = read('src/workspace/editorBridge.ts')
const tauriLib = read('src-tauri/src/lib.rs')
const workspaceStore = read('src/workspace/workspaceStore.ts')
const capability = JSON.parse(read('src-tauri/capabilities/default.json'))

assert.match(main, /windowType === ['"]quick-editor['"][\s\S]*QuickEditorDetachedView/, 'main entry must render QuickEditorDetachedView for ?window=quick-editor')
assert.match(editorWindowApi, /closeQuickEditorWindow\(\)/, 'frontend editor closer must delegate lifecycle to native runtime')
assert.match(editorWindowApi, /markSurfaceInstanceState\(.*QUICK_EDITOR_WINDOW_LABEL,\s*['"]destroyed['"]\)/, 'frontend editor closer must mark editor surface destroyed using the centralized label')
assert.doesNotMatch(editorWindowApi, /new WebviewWindow|WebviewWindow\.getByLabel/, 'frontend must not create editor windows directly')
assert.match(editorWindowApi, /showQuickEditorWindow\(\)/, 'editor window API must forward to Quick Editor window manager')
assert.match(editorWindowApi, /upsertSurfaceInstance/, 'editor window API must register surface instances')
assert.match(editorBridge, /EDITOR_BRIDGE_REQUEST_EVENT/, 'editor bridge must define a request event')
assert.match(editorBridge, /EDITOR_BRIDGE_RESPONSE_EVENT/, 'editor bridge must define a response event')
assert.match(editorBridge, /EDITOR_BRIDGE_READY_EVENT/, 'editor bridge must define a ready event')
assert.match(editorBridge, /getEditorContext/, 'editor bridge must expose getEditorContext')
assert.match(editorBridge, /createEditorPane/, 'editor bridge must expose createEditorPane')
assert.match(editorBridge, /replaceEditorSelection/, 'editor bridge must expose replaceEditorSelection')
assert.match(editorBridge, /insertIntoEditor/, 'editor bridge must expose insertIntoEditor')
assert.match(editorBridge, /openEditorPanel/, 'editor bridge must expose openEditorPanel')
assert.match(editorBridge, /localStorage\.setItem\(EDITOR_BRIDGE_PENDING_REQUESTS_KEY/, 'editor bridge must persist pending requests for newly-created editor windows')
assert.match(editorBridge, /emit\(EDITOR_BRIDGE_REQUEST_EVENT/, 'editor bridge must emit requests to already-running editor windows through the centralized label')
assert.match(editorBridge, /waitForEditorBridgeResponse/, 'editor bridge must wait for explicit responses')
assert.match(editorBridge, /waitForEditorBridgeReady/, 'editor bridge must wait for editor handler readiness before sending startup-sensitive requests')
assert.match(editorBridge, /request = createEditorBridgeRequest[\s\S]*persistPendingEditorBridgeRequest\(request\)[\s\S]*showEditorWindow\(\)/, 'editor bridge must persist startup-sensitive requests before opening the editor window')
assert.match(editorBridge, /registerActiveEditorContext/, 'editor bridge must expose active context registration')
assert.match(editorBridge, /updateActivePaneSnapshot/, 'editor bridge must expose active pane snapshot updates')
assert.match(editorBridge, /clearActiveEditorSnapshots/, 'editor bridge must expose active context cleanup for editor teardown')
assert.match(editorBridge, /isPendingEditorBridgeRequest/, 'editor bridge must avoid duplicate live delivery after startup pending queue consumption')
assert.doesNotMatch(editorBridge, /useWorkspaceStore|getState\(\)\.createPane|getState\(\)\.openPanelV2/, 'editor bridge caller side must not mutate editor workspace state directly')
assert.match(tauriLib, /async fn show_quick_editor_window/, 'native runtime must expose show_quick_editor_window')
assert.match(tauriLib, /get_webview_window\(QUICK_EDITOR_WINDOW_LABEL\)/, 'editor window must be singleton and reuse existing windows')
assert.match(tauriLib, /WebviewUrl::App\("index\.html\?window=quick-editor"/, 'editor window must route to ?window=quick-editor')
assert.match(tauriLib, /inner_size\(QUICK_EDITOR_WINDOW_WIDTH,\s*QUICK_EDITOR_WINDOW_HEIGHT\)/, 'editor window must have explicit default size')
assert.match(tauriLib, /min_inner_size\(\s*QUICK_EDITOR_WINDOW_MIN_WIDTH,\s*QUICK_EDITOR_WINDOW_MIN_HEIGHT/, 'editor window must have explicit minimum size')
assert.match(tauriLib, /show_quick_editor_window[\s\S]*set_focus/, 'show_quick_editor_window must focus the editor window')
assert.ok(capability.windows.some((w) => w.startsWith('editor')), 'capability scope must allow the editor window')

assert.match(quickEditorView, /QuickEditorPanel/, 'QuickEditorDetachedView must host QuickEditorPanel')
assert.match(quickEditorView, /loadInstalledPluginsFromStore/, 'QuickEditorDetachedView must load plugins')
assert.match(quickEditorView, /closeQuickEditorWindow/, 'QuickEditorDetachedView must support window close')
assert.match(editorWindowManager, /function\s+showEditorWindow\(\)[\s\S]*requestOpenEditorWindow\(\)/, 'editor window manager must expose an open facade')
assert.match(editorWindowManager, /function\s+closeEditorWindow\([\s\S]*requestCloseEditorWindow\(/, 'editor window manager must expose a close facade')
assert.match(editorBridge, /showEditorWindow\(\)/, 'editor bridge must open editor windows through the window manager facade')
assert.doesNotMatch(editorBridge, /requestOpenEditorWindow/, 'editor bridge must not call the lower-level lifecycle API directly')
assert.match(workspaceStore, /isEditorWindowWorkspaceSession[\s\S]*sessionStorage/, 'editor workspace state must use session storage for scratch sessions')

console.log('editor window launch checks passed')
