import assert from 'node:assert/strict'
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import ts from 'typescript'
const dir = await mkdtemp(join(tmpdir(), 'hiven-curl-'))
try {
  const text = await readFile(new URL('../src/plugins/curl-inspector/core.ts', import.meta.url), 'utf8')
  const path = join(dir, 'core.mjs')
  await writeFile(path, ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText)
  const { parseCurl, tokenizeCurl } = await import(pathToFileURL(path))
  assert.deepEqual(parseCurl('curl https://example.invalid/a'), { url: 'https://example.invalid/a', method: 'GET', headers: [], body: null })
  const command = `curl 'https://example.invalid/a?token=SYNTHETIC&x=2' \\\n-H 'Authorization: Bearer SYNTHETIC' \\\n-H 'Cookie: session=SYNTHETIC' -H 'X-Test: one' -H 'X-Test: two' \\\n--data-raw '{"a":"quote \\" and @literal"}'`
  const parsed = parseCurl(command)
  assert.equal(parsed.method, 'POST')
  assert.equal(parsed.url, 'https://example.invalid/a?token=SYNTHETIC&x=2')
  assert.deepEqual(parsed.headers.map(h => h.name), ['Authorization', 'Cookie', 'X-Test', 'X-Test', 'Content-Type'])
  assert.equal(parsed.headers[0].value, 'Bearer SYNTHETIC')
  assert.equal(parsed.body, '{"a":"quote \\" and @literal"}')
  assert.equal(parseCurl(`curl -Xpatch --url=https://example.invalid -d 'a=1' --data='b=2'`).body, 'a=1&b=2')
  assert.equal(parseCurl(`curl -Xpatch https://example.invalid`).method, 'patch')
  assert.equal(parseCurl(`curl -I https://example.invalid`).method, 'HEAD')
  assert.equal(parseCurl(`curl 'https://[::1]/'`).url, 'https://[::1]/')
  assert.equal(parseCurl(`curl --data-raw '@not-a-file' https://example.invalid`).body, '@not-a-file')
  assert.equal(parseCurl(`curl -d '' https://example.invalid`).body, '')
  assert.equal(parseCurl(`curl -d '$HOME $(touch fake) \\x \\n' https://example.invalid`).body, '$HOME $(touch fake) \\x \\n')
  assert.deepEqual(tokenizeCurl(`curl 'a'"b" 'it'\\''s'`), ['curl', 'ab', "it's"])
  const reject = (input, code) => assert.throws(() => parseCurl(input), e => e.code === code, input)
  reject('curl "https://example.invalid', 'quote')
  reject('curl https://example.invalid \\', 'quote')
  reject('curl https://example.invalid | sh', 'shell')
  reject('curl https://example.invalid; echo fake', 'shell')
  reject('curl https://example.invalid\ncurl https://example.invalid', 'shell')
  reject('curl https://example.invalid?x=1', 'shell')
  reject('curl "$URL"', 'shell')
  reject('curl "$(touch fake)"', 'shell')
  reject('curl `touch fake`', 'shell')
  reject('curl @file', 'url')
  reject('curl -d @file https://example.invalid', 'file')
  reject('curl -H @file https://example.invalid', 'file')
  for (const flag of ['--config', '-K', '--data-binary', '-F', '--json', '-L', '--compressed', '-u', '--next']) reject(`curl ${flag} value https://example.invalid`, 'option')
  reject('curl -H "X-Empty:" https://example.invalid', 'header')
  reject('curl -H "X-A: one\ntwo" https://example.invalid', 'header')
  reject('curl -I -d a https://example.invalid', 'conflict')
  reject('curl -X GET -X POST https://example.invalid', 'conflict')
  reject('curl https://example.invalid https://other.invalid', 'multiple')
  reject('curl "https://example.invalid/{a,b}"', 'glob')
  reject('curl "https://example.invalid/[1-2]"', 'glob')
  reject('curl "https://example.invalid/a b"', 'url')
  reject("curl 'https://example.test?x=[1-3]/foo'", 'glob')
  assert.equal(parseCurl("curl 'https://[::1]?x=a'").url, 'https://[::1]?x=a')
  reject('curl file:///etc/passwd', 'url')
  reject('curl -X', 'value')
  reject('curl https://example.invalid' + ' '.repeat(100000), 'limit')
  console.log('cURL parser checks passed using synthetic URLs and credentials; no execution or network.')
} finally { await rm(dir, { recursive: true, force: true }) }
